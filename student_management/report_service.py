"""Generate shareable report files from the repository data."""
import csv
import html
from pathlib import Path
from .academic_service import class_statistics, student_summary
from .config import SUBJECTS


def write_student_report(student, destination: str | Path) -> Path:
    """Write an accessible standalone HTML report for one student."""
    destination = Path(destination)
    summary = student_summary(student)
    mark_rows = "\n".join(
        f"<tr><th>{html.escape(subject)}</th><td>{student.marks[subject]}</td></tr>" for subject in SUBJECTS
    )
    recommendations = "\n".join(
        f"<li>{html.escape(item)}</li>" for item in _recommendations(student)
    )
    page = f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width">
<title>Student report - {html.escape(student.name)}</title>
<style>body{{font:16px/1.5 Arial,sans-serif;max-width:760px;margin:32px auto;padding:0 20px;color:#202033}}h1{{color:#5935a5}}table{{width:100%;border-collapse:collapse}}td,th{{padding:8px;border:1px solid #ddd;text-align:left}}th{{background:#f1edff}}.meta{{padding:14px;background:#f8f6ff;border-radius:8px}}</style>
</head><body><h1>Student Performance Report</h1>
<div class="meta"><strong>{html.escape(student.name)}</strong><br>Roll number: {html.escape(student.roll_no)}<br>Course: {html.escape(student.course)}<br>Age: {student.age}<br>Average: {summary['average']}% | Grade: {summary['grade']} | Status: {'Pass' if summary['passed'] else 'Needs improvement'}</div>
<h2>Subject marks</h2><table><thead><tr><th>Subject</th><th>Marks / 100</th></tr></thead><tbody>{mark_rows}</tbody></table>
<h2>Study recommendations</h2><ul>{recommendations}</ul>
<p><small>Generated by AI Powered Student Management System. Recommendations are rule-based and should support, not replace, teacher guidance.</small></p>
</body></html>"""
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(page, encoding="utf-8")
    return destination


def _recommendations(student) -> list[str]:
    from .recommendation_service import recommend_for_student
    return recommend_for_student(student)["actions"]


def write_class_report(students, destination: str | Path) -> Path:
    """Write a CSV report containing aggregate metrics and student rankings."""
    destination = Path(destination)
    records = list(students)
    stats = class_statistics(records)
    destination.parent.mkdir(parents=True, exist_ok=True)
    with destination.open("w", newline="", encoding="utf-8-sig") as handle:
        writer = csv.writer(handle)
        writer.writerow(["AI Powered Student Management System - Class Report"])
        writer.writerow(["Students", stats["student_count"]])
        writer.writerow(["Class average", stats["class_average"]])
        writer.writerow(["Pass percentage", stats["pass_percentage"]])
        writer.writerow([])
        writer.writerow(["Rank", "Roll number", "Name", "Course", "Average", "Grade", "Passed"])
        ranked = sorted(records, key=lambda item: (-item.average, item.name.casefold()))
        for rank, student in enumerate(ranked, start=1):
            writer.writerow([rank, student.roll_no, student.name, student.course, student.average,
                             student.grade, "Yes" if student.passed else "No"])
    return destination
